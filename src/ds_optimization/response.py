"""Кривая отклика урожайности на дозу удобрения, §2.4.2.

Продолжает прогноз модели L4 (Y_base) агрономическим законом убывающей
отдачи (модель Митчерлиха), а не заменяет его.
"""

import numpy as np


def yield_response(baseline, R, s, d):
    """Y_k(d) = baseline + R * (1 - exp(-d/s)).

    baseline : базовый потенциал урожайности участка без доп. внесения (Y_base из L4).
    R : предельный дополнительный урожай при неограниченной дозе.
    s : масштаб насыщения (чем меньше, тем быстрее выходит на плато).
    d : доза (скаляр или np.ndarray).
    """
    return baseline + R * (1.0 - np.exp(-np.asarray(d) / s))


def marginal_response(R, s, d):
    """dY/dd в точке d -- предельная прибавка урожая на единицу дозы."""
    return (R / s) * np.exp(-np.asarray(d) / s)
